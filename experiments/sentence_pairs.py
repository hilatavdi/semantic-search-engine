"""Part E: embedding similarity for sentence pairs of three kinds.

Usage (from the project root):
    python experiments/sentence_pairs.py

The three required pairs share the same anchor sentence ("I want to cancel my subscription."), so
the only thing that changes between them is the second sentence. Extra pairs per category check that
the pattern is not a one-off. Predictions were written down BEFORE running the script and are
printed next to the measured values.

For comparison we also print the Part D cross-encoder score for each pair.

Writes the results to experiments/part_e_results.md.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
os.environ.setdefault("TRANSFORMERS_VERBOSITY", "error")
os.environ.setdefault("TQDM_DISABLE", "1")
os.environ.setdefault("HF_HUB_VERBOSITY", "error")

from semantic_search.embeddings import SentenceTransformerEmbedder
from semantic_search.ranking import cosine_similarities
from semantic_search.reranker import CrossEncoderReranker

OUT = Path(__file__).resolve().parent / "part_e_results.md"
ANCHOR = "I want to cancel my subscription."

# (category, sentence A, sentence B, predicted cosine range written before running)
REQUIRED_PAIRS = [
    ("1. Similar meaning", ANCHOR, "How do I stop my membership?", "0.60 - 0.80"),
    ("2. Same topic, different intent", ANCHOR, "I want to upgrade my subscription.", "0.50 - 0.70"),
    ("3. Unrelated", ANCHOR, "I am looking for a short hiking trail suitable for children.", "0.00 - 0.15"),
]

EXTRA_PAIRS = [
    ("1. Similar meaning", "My package hasn't arrived yet.", "I'm still waiting for my delivery.", "0.55 - 0.75"),
    ("1. Similar meaning", "I forgot my password.", "I can't remember my login details.", "0.50 - 0.70"),
    ("2. Same topic, different intent", "How do I turn on notifications?", "How do I turn off notifications?", "0.80 - 0.95"),
    ("2. Same topic, different intent", "I received my refund.", "I did not receive my refund.", "0.80 - 0.95"),
    ("2. Same topic, different intent", "I want to return this jacket.", "I want to buy this jacket.", "0.60 - 0.80"),
    ("3. Unrelated", "The app crashes when I open it.", "Where can I find a good pizza place?", "0.00 - 0.15"),
    ("3. Unrelated", "My credit card was declined.", "I want to learn Python from scratch.", "0.00 - 0.15"),
]


def main() -> None:
    embedder = SentenceTransformerEmbedder()
    reranker = CrossEncoderReranker()

    def measure(pairs):
        rows = []
        for cat, a, b, pred in pairs:
            vecs = embedder.embed([a, b])
            cos = float(cosine_similarities(vecs[0], vecs[1:])[0])
            ce = float(reranker.score(a, [b])[0])
            lo, hi = (float(x) for x in pred.split(" - "))
            verdict = "as expected" if lo <= cos <= hi else ("higher than expected" if cos > hi else "lower than expected")
            rows.append((cat, a, b, pred, cos, ce, verdict))
        return rows

    def table(rows):
        out = ["| Category | Sentence A | Sentence B | Predicted cosine | **Cosine** | vs. prediction | Cross-encoder |",
               "|---|---|---|---|---|---|---|"]
        for cat, a, b, pred, cos, ce, verdict in rows:
            out.append(f"| {cat} | {a} | {b} | {pred} | **{cos:.3f}** | {verdict} | {ce:.2f} |")
        return out

    required, extra = measure(REQUIRED_PAIRS), measure(EXTRA_PAIRS)
    lines = ["# Part E - Sentence pair similarity: raw results", "",
             "Generated by `experiments/sentence_pairs.py`. Cosine = similarity of `all-MiniLM-L6-v2` "
             "embeddings (the score the search engine uses). Cross-encoder = Part D reranker score "
             "(`ms-marco-MiniLM-L-12-v2`, raw logit), shown for comparison only.", "",
             "## The three required pairs", ""] + table(required) + [
             "", "## Extra pairs (to check the pattern holds beyond one example)", ""] + table(extra) + [""]

    all_rows = required + extra
    lines += ["## Average cosine per category (all pairs)", "", "| Category | Pairs | Mean cosine | Min | Max |",
              "|---|---|---|---|---|"]
    for cat in sorted({r[0] for r in all_rows}):
        vals = [r[4] for r in all_rows if r[0] == cat]
        lines.append(f"| {cat} | {len(vals)} | {sum(vals) / len(vals):.3f} | {min(vals):.3f} | {max(vals):.3f} |")
    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)
    print(f"Saved to {OUT}")


if __name__ == "__main__":
    main()
