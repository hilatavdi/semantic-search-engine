"""Part D: search results before (semantic only) and after (semantic + cross-encoder reranking).

Usage (from the project root):
    python experiments/rerank_before_after.py

For each query we also list which documents we judged relevant (a manual judgement, stated up
front so it can be challenged) and compute two simple metrics:
    - First relevant rank: position of the first relevant document in the top 5 (lower is better).
    - Relevant in top 5:   how many of the top 5 results are relevant (higher is better).

Writes the full results to experiments/part_d_results.md.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
os.environ.setdefault("TRANSFORMERS_VERBOSITY", "error")
os.environ.setdefault("TQDM_DISABLE", "1")
os.environ.setdefault("HF_HUB_VERBOSITY", "error")

from semantic_search.data_loader import load_documents
from semantic_search.embeddings import SentenceTransformerEmbedder
from semantic_search.reranker import CrossEncoderReranker, RerankingSearchEngine
from semantic_search.search import SemanticSearchEngine

DATA = ROOT / "data" / "semantic_search_sample_data_en.json"
OUT = Path(__file__).resolve().parent / "part_d_results.md"

# query -> ids we judged relevant (would actually help a user with this request)
QUERIES = {
    "I want to cancel my subscription": {"doc_001", "doc_002", "doc_005"},
    "turn off notifications": {"doc_060"},
    "stop getting emails from you": {"doc_060"},
    "How do I end my plan?": {"doc_001", "doc_002", "doc_005"},
    "I can't log into my account": {"doc_009", "doc_010", "doc_014"},
    "my parcel never showed up": {"doc_017", "doc_018", "doc_021", "doc_024"},
    "cancel my booking": {"doc_052"},
    "I want to upgrade my subscription": {"doc_003"},
}


def metrics(results, relevant):
    ranks = [r.rank for r in results if r.id in relevant]
    return (ranks[0] if ranks else None), len(ranks)


def fmt_first(x):
    return str(x) if x is not None else "not in top 5"


def main() -> None:
    docs = load_documents(DATA)
    category = {d.id: d.category for d in docs}
    semantic = SemanticSearchEngine(docs, SentenceTransformerEmbedder())
    reranked = RerankingSearchEngine(semantic, CrossEncoderReranker(), num_candidates=15)

    summary = ["| Query | First relevant rank: before -> after | Relevant in top 5: before -> after |",
               "|---|---|---|"]
    details = []
    for q, relevant in QUERIES.items():
        before, after = semantic.search(q, 5), reranked.search(q, 5)
        (fb, nb), (fa, na) = metrics(before, relevant), metrics(after, relevant)
        summary.append(f"| {q} | {fmt_first(fb)} -> {fmt_first(fa)} | {nb} -> {na} |")

        details += [f"## Query: \"{q}\"", "", f"Judged relevant: {', '.join(sorted(relevant))}", ""]
        for label, results, unit in (("Before - semantic only", before, "cosine"),
                                     ("After - reranked", after, "cross-encoder")):
            details += [f"**{label}** (score = {unit})", "",
                        "| # | id | score | relevant | category | text |", "|---|---|---|---|---|---|"]
            for r in results:
                mark = "yes" if r.id in relevant else ""
                details.append(f"| {r.rank} | {r.id} | {r.score:.3f} | {mark} | {category[r.id]} | {r.text} |")
            details.append("")

    text = "\n".join(["# Part D - Before / after cross-encoder reranking: raw results", "",
                      "Generated by `experiments/rerank_before_after.py`. Before = semantic search "
                      "(cosine similarity). After = top 15 semantic candidates re-scored by "
                      "`cross-encoder/ms-marco-MiniLM-L-12-v2` (raw logit: higher = more relevant; "
                      "only the order matters, not the absolute value).", "",
                      "## Summary", ""] + summary + [""] + details)
    OUT.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nSaved to {OUT}")


if __name__ == "__main__":
    main()
