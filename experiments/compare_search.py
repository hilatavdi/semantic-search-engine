"""Part C: run the same queries through semantic and keyword search, side by side.

Usage (from the project root):
    python experiments/compare_search.py                 # default query set, prints + saves markdown
    python experiments/compare_search.py "query 1" "query 2"

Writes the full results to experiments/part_c_results.md.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
os.environ.setdefault("TRANSFORMERS_VERBOSITY", "error")
os.environ.setdefault("TQDM_DISABLE", "1")
os.environ.setdefault("HF_HUB_VERBOSITY", "error")

from semantic_search.data_loader import load_documents
from semantic_search.embeddings import SentenceTransformerEmbedder
from semantic_search.keyword_search import KeywordSearchEngine, tokenize
from semantic_search.search import SemanticSearchEngine

DATA = ROOT / "data" / "semantic_search_sample_data_en.json"
OUT = Path(__file__).resolve().parent / "part_c_results.md"

DEFAULT_QUERIES = [
    "my parcel never showed up",
    "I can't log into my account",
    "the app is not working",
    "cancel my booking",
    "How do I end my plan?",
    "turn off notifications",
    "I want to cancel my subscription",
]


def main(queries: list[str]) -> None:
    docs = load_documents(DATA)
    category = {d.id: d.category for d in docs}
    semantic = SemanticSearchEngine(docs, SentenceTransformerEmbedder())
    keyword = KeywordSearchEngine(docs)

    lines = ["# Part C - Semantic vs. keyword search: raw results", "",
             "Generated by `experiments/compare_search.py`. Top 5 per engine; "
             "keyword score = share of query keywords found in the text.", ""]
    for q in queries:
        lines += [f"## Query: \"{q}\"", "", f"Keywords after stop-word removal: `{tokenize(q)}`", ""]
        for label, engine in (("Semantic", semantic), ("Keyword", keyword)):
            results = engine.search(q, 5)
            lines += [f"**{label}**", "", "| # | id | score | category | text |", "|---|---|---|---|---|"]
            if not results:
                lines.append("| - | - | - | - | *(no document contains any of the keywords)* |")
            for r in results:
                lines.append(f"| {r.rank} | {r.id} | {r.score:.3f} | {category[r.id]} | {r.text} |")
            lines.append("")
    text = "\n".join(lines)
    OUT.write_text(text, encoding="utf-8")
    print(text)
    print(f"\nSaved to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1:] or DEFAULT_QUERIES)
